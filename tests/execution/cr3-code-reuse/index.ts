import {
  at,
  check,
  equal,
  PC,
  ROOT_A,
  ROOT_B,
  withRoots,
  type Family,
  type Scenario,
} from './fixture.js';
import { sourceScenarios } from './sources.js';
import { controlScenarios } from './controls.js';
import { bindingScenarios } from './bindings.js';
import {
  GDT,
  IRET_B,
  RESUME_A,
  TSS_B,
  toCaller,
  withGuest,
  write32,
} from '../task-switching/fixture.js';

function alternating(
  compiler: WebAssembly.Module,
  family: Family,
  capacity: number,
  restricted = false,
): Scenario {
  return {
    name: `CR3 code reuse ${family} ${restricted ? 'restricted' : 'physical'} alternates private instructions and data at artifact capacity ${capacity}`,
    async run() {
      await withRoots(
        compiler,
        family,
        async (cpu) => {
          const tsc = cpu.readTimeState().tsc;
          for (let half = 0; half < 8; half++) {
            const fromA = half % 2 === 0;
            const budget = half === 0 ? 4n : 5n;
            const result = await cpu.run({ budget });
            equal(result.reason, 'budget', 'exact half completed');
            equal(result.retired, budget, 'short jump, private load, literals and root write');
            equal(result.state.rip, PC + 20n, 'successor belongs to incoming root');
            equal(
              result.state.registers[1],
              fromA ? 0x110011aan : 0x220022bbn,
              'private instruction',
            );
            equal(result.state.registers[2], fromA ? 0xaabbccddn : 0x44332211n, 'private data');
            equal(cpu.readPagingState().cr3, fromA ? ROOT_B : ROOT_A, 'incoming address space');
            check(result.resources.cachedArtifacts <= capacity, 'bounded resident translations');
            if (half >= 2) {
              equal(result.resources.compilations, capacity === 1 ? 1 : 0, 'returning variant');
              equal(result.resources.cacheHits, capacity === 1 ? 0 : 1, 'returning native entry');
              equal(result.resources.generatedBytes === 0, capacity === 2, 'generated bytes');
            }
          }
          equal(cpu.readTimeState().tsc - tsc, 39n, 'all committed work charged once');
          // Direct entry to the second MOV of the retained A body skips the first load.
          at(cpu, PC + 7n);
          const middle = await cpu.run({ budget: 1n });
          equal(middle.state.registers[1], 0x110011aan, 'A literal at middle entry');
          equal(middle.state.registers[2], 0x44332211n, 'skipped load retains last B value');
          equal(middle.resources.compilations, capacity === 1 ? 1 : 0, 'middle-entry ownership');
        },
        { capacity, restricted },
      );
    },
  };
}

export function cr3CodeReuseScenarios(compiler: WebAssembly.Module): Scenario[] {
  return [
    ...(['non-PAE', 'PAE', 'IA32e'] as const).map((family) => alternating(compiler, family, 2)),
    alternating(compiler, 'IA32e', 1),
    alternating(compiler, 'IA32e', 2, true),
    ...sourceScenarios(compiler),
    ...controlScenarios(compiler),
    ...bindingScenarios(compiler),
    {
      name: 'CR3 code reuse retains nested CALL and IRET owners across different roots and task registers',
      async run() {
        await withGuest(compiler, async (cpu) => {
          await toCaller(cpu);
          write32(cpu, TSS_B + 84n, 0x10);
          write32(cpu, TSS_B + 32n, Number(IRET_B + 1n));
          cpu.writePhysicalMemory(RESUME_A, Uint8Array.of(0xeb, 0xf7)); // JMP to CALL
          cpu.writePhysicalMemory(IRET_B + 1n, Uint8Array.of(0xeb, 0xfd)); // JMP to IRETD
          const tsc = cpu.readTimeState().tsc;
          const start = await cpu.run({ budget: 1n });
          equal(start.state.rip, IRET_B + 1n, 'first CALL enters B');
          for (let half = 0; half < 7; half++) {
            const returning = half % 2 === 0;
            const result = await cpu.run({ budget: 2n });
            equal(result.reason, 'budget', 'two instructions');
            equal(result.retired, 2n, 'short jump and transfer');
            equal(result.state.rip, returning ? RESUME_A : IRET_B + 1n, 'incoming task PC');
            equal(cpu.readContext().tr.selector, returning ? 0x18 : 0x20, 'incoming TR');
            equal(cpu.readPagingState().cr3, returning ? 0x20000n : 0x21000n, 'task root');
            equal(cpu.readPhysicalMemory(GDT + 0x25n, 1)[0], returning ? 0x89 : 0x8b, 'B busy bit');
            if (half >= 3) {
              equal(result.resources.compilations, 0, 'warmed task root and context');
              equal(result.resources.generatedBytes, 0, 'no regenerated task unit');
              equal(result.resources.cacheHits, 1, 'guest entered a retained owner');
            }
          }
          equal(cpu.readTimeState().tsc - tsc, 15n, 'one CALL then seven pairs of instructions');
        });
      },
    },
  ];
}
